'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const app = path.resolve(__dirname,'..');
const scratch = path.resolve(process.argv[2]);
const read = file => JSON.parse(fs.readFileSync(file,'utf8'));
const hash = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const manifestPath = path.join(app,'data/audio-manifest.json');
const timingPath = path.join(app,'data/read-along.json');
const manifest = read(manifestPath), timing = read(timingPath);
const rows = read(path.join(scratch,'plan.json'));
manifest.items = [];
manifest.voices.ar = 'SILMA TTS 1.0.5';
manifest.voices.en = 'SILMA TTS 1.0.5';
let speechCues = 0, sentence = 0;
for (const row of rows) {
  const entry = read(path.join(scratch,row.id+'.json'));
  assert.equal(entry.text,row.text);
  assert.equal(entry.sha256,hash(path.join(app,row.path)));
  assert.equal(entry.path,row.path);
  assert.equal(entry.engine,'silma-tts-1.0.5');
  manifest.items.push(entry);
  const candidates = ['.mms.json','.timing.json'].map(suffix => path.join(scratch,row.id+suffix));
  const checked = candidates.filter(file => fs.existsSync(file)).map(read).filter(record => record.audio_sha256 === entry.sha256);
  const cue = checked.find(record => record.cues.length) || checked[0];
  assert.ok(cue, 'No acoustic review for ' + row.id);
  assert.equal(cue.text,row.text);
  assert.equal(cue.duration,entry.duration_ms);
  if (cue.cues.length) speechCues++;
  else sentence++;
  delete cue.recognition;
  timing.items[row.path] = cue;
}
manifest.items.sort((a,b) => a.id.localeCompare(b.id,'en'));
fs.writeFileSync(manifestPath,JSON.stringify(manifest,null,2)+'\n');
fs.writeFileSync(timingPath,JSON.stringify(timing)+'\n');
console.log(`${rows.length} updated clips; ${speechCues} measured word tracks, ${sentence} sentence tracks`);
