"""Align authored SILMA text to its exact MP3 using Whisper attention DTW.
Independent ASR is retained for review; it is not proof of human pronunciation.
Resumes by MP3 SHA and waits briefly for an active generation run when --follow.
"""
import pathlib,json,hashlib,subprocess,re,sys,time
import numpy as np
from faster_whisper import WhisperModel
from faster_whisper.tokenizer import Tokenizer
from faster_whisper.audio import pad_or_trim
ROOT=pathlib.Path(__file__).resolve().parents[1]
model=WhisperModel(sys.argv[1],device='cpu',compute_type='int8',cpu_threads=2,local_files_only=True)
cuefile=ROOT/'coach/audio-cues.json'; rows=json.loads(cuefile.read_text()) if cuefile.exists() else {}
qa_file=ROOT/'tools/coach-asr.json';qa=json.loads(qa_file.read_text()) if qa_file.exists() else {}
plan=json.loads((ROOT/'tools/coach-plan.json').read_text())['clips']
def norm(s):
 s=re.sub('[أإآٱ]','ا',s.lower()).replace('ى','ي')
 return re.sub(r'[^\w]','',re.sub('[\u064b-\u065f\u0670ـ]','',s),flags=re.UNICODE).replace('_','')
def write():
 cuefile.write_text(json.dumps(rows,ensure_ascii=False,indent=2)+'\n')
 (ROOT/'coach/audio-cues.js').write_text('/* Actual SILMA waveform word cues; generated by tools/align-coach.py. */\nwindow.DrawingCoachAudio='+json.dumps(rows,ensure_ascii=False,separators=(',',':'))+';\n')
 qa_file.write_text(json.dumps(qa,ensure_ascii=False,indent=2)+'\n')
expected={r['id']:r for r in plan}
rows={k:v for k,v in rows.items() if k in expected};qa={k:v for k,v in qa.items() if k in expected}
idle=0
while True:
 try:clips=json.loads((ROOT/'audio/coach/manifest.json').read_text())['clips']
 except (FileNotFoundError,json.JSONDecodeError):clips=[]
 changed=False
 for c in clips:
  if c['id'] not in expected or c['text']!=expected[c['id']]['text']:continue
  p=ROOT/c['path'];digest=hashlib.sha256(p.read_bytes()).hexdigest()
  if c['sha256']!=digest:continue
  if c['id'] in rows and rows[c['id']]['sha256']==digest:continue
  raw=subprocess.check_output(['ffmpeg','-v','error','-i',str(p),'-ar','16000','-ac','1','-f','f32le','-']);pcm=np.frombuffer(raw,dtype=np.float32).copy();duration=len(pcm)/16000
  text=c['text'];plain=re.sub('[\u064b-\u065f\u0670ـ]','',text);tokenizer=Tokenizer(model.hf_tokenizer,True,task='transcribe',language=c.get('language','ar'))
  features=model.feature_extractor(pcm);encoder=model.encode(pad_or_trim(features));tokens=tokenizer.encode(' '+plain)
  aligned=model.find_alignment(tokenizer,[tokens],encoder,min(3000,len(pcm)//160))[0]
  targets=text.split();sizes=[len(norm(t)) for t in targets];flat=''.join(norm(t) for t in targets);cursor=0;spans={};transcribed=''
  for word in aligned:
   v=norm(word['word'])
   if not v:continue
   assert flat[cursor:cursor+len(v)]==v,(c['id'],flat,cursor,v)
   offset=0
   for i,size in enumerate(sizes):
    if offset<cursor+len(v) and offset+size>cursor:
     if i not in spans:spans[i]=[max(0,word['start']),min(duration,word['end'])]
     else:spans[i][1]=max(spans[i][1],min(duration,word['end']))
    offset+=size
   cursor+=len(v)
  assert cursor==len(flat) and len(spans)==len(targets),(c['id'],cursor,len(flat),len(spans),len(targets))
  cues=[[i,round(a*1000),round(max(a+.01,b)*1000)] for i,(a,b) in sorted(spans.items())]
  segments,_=model.transcribe(pcm,language=c.get('language','ar'),beam_size=3,word_timestamps=True,vad_filter=False,condition_on_previous_text=False)
  seg=list(segments);asr=' '.join(s.text.strip() for s in seg);words=[{'text':w.word,'start':w.start,'end':w.end,'probability':round(w.probability,3)} for s in seg for w in (s.words or [])]
  rows[c['id']]={'path':c['path'],'text':text,'language':c.get('language','ar'),'duration':round(duration*1000),'cues':cues,'sha256':digest,'timing_source':'Whisper-small forced attention DTW on authored text and exact decoded MP3'}
  qa[c['id']]={'asr':asr,'words':words,'sha256':digest,'expected_last_word':targets[-1],'last_word_found':norm(targets[-1]) in norm(asr),'note':'Independent ASR is a review aid; short isolated letter names can be ambiguous.'}
  changed=True;write();print('Aligned',c['id'],'ASR:',asr,flush=True)
 if len(rows)>=len(plan):break
 if '--follow' not in sys.argv:break
 idle=0 if changed else idle+1
 if idle>400:raise RuntimeError('Generation wait exceeded')
 time.sleep(3)
for id,entry in qa.items():
 spec=expected.get(id,{})
 heard=entry['asr']
 if spec.get('language')=='en':
  words=['zero','one','two','three','four','five','six','seven','eight','nine','ten']
  heard=re.sub(r'\b(?:10|[0-9])\b',lambda m:words[int(m.group())],heard)
 keyword=spec.get('keyword') or spec.get('text','').split()[-1]
 entry['expected_keyword']=keyword;entry['keyword_found']=norm(keyword) in norm(heard)
write()
print('Cue entries:',len(rows),flush=True)
